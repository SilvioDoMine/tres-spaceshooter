import { createHash } from 'node:crypto';
import { readdirSync,readFileSync,writeFileSync } from 'node:fs';
const root=new URL('../',import.meta.url);
const revisions={};
for(const file of readdirSync(new URL('public/models/enemies/',root)).filter(f=>/^c[1-5]_\w+\.glb$/.test(f))){
  revisions[file.slice(0,-4)]=createHash('sha256').update(readFileSync(new URL('public/models/enemies/'+file,root))).digest('hex').slice(0,12);
}
writeFileSync(new URL('app/data/fleetModelRevisions.js',root),'// Generated by scripts/version-chapter-fleets.mjs; includes summoned units.\nexport const FLEET_MODEL_REVISIONS = '+JSON.stringify(revisions,null,2)+';\n');
