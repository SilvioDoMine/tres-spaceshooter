import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const fleet = {};
mkdirSync(resolve(root, 'public/models/enemies'), { recursive: true });
for (const batch of ['02', '03']) {
  const folder = resolve(root, `art/enemies/frota-${batch}`);
  for (const entry of JSON.parse(readFileSync(resolve(folder, 'manifest.json'), 'utf8'))) {
    const bytes = readFileSync(resolve(folder, entry.asset));
    const gltf = JSON.parse(bytes.subarray(20, 20 + bytes.readUInt32LE(12)));
    const sockets = entry.sockets.map(socket => {
      const index = gltf.nodes.findIndex(node => node.extras?.role === socket.name);
      if (index < 0) throw new Error(`Missing socket ${entry.enemy}/${socket.name}`);
      const parent = gltf.nodes.find(node => node.children?.includes(index));
      return { role: socket.name, position: socket.position_glTF, direction: socket.direction_glTF,
        group: parent?.name?.replace(/\.\d+$/, '') };
    });
    copyFileSync(resolve(folder, entry.asset), resolve(root, 'public/models/enemies', entry.asset));
    fleet[entry.enemy] = { name: entry.name, url: `/models/enemies/${entry.asset}`, sockets };
  }
}
writeFileSync(resolve(root, 'app/data/enemyFleetCatalog.js'),
  '// Generated by scripts/sync-enemy-fleet.mjs from the Blender export manifests.\n'
  + 'export const ENEMY_FLEET = ' + JSON.stringify(fleet, null, 2) + ';\n');
console.log(`Published ${Object.keys(fleet).length} enemy models and their physical hardpoints.`);
